/**
 * Адрес клиента — с **доверенного** хопа, а не с того, который назвал сам клиент.
 *
 * `X-Forwarded-For` собирается прокси как «то, что прислал клиент, + реальный peer»,
 * поэтому **первый** элемент списка подконтролен атакующему: подставив его, аноним
 * получал свежую корзину на каждый запрос и обнулял все лимиты (rate-limit UGC/чата/
 * заявок, дедуп жалоб, порог авто-скрытия), а `ipHash` переставал что-либо значить.
 * Раньше брался именно первый элемент — оттуда и класс G413 «IP из заголовка»
 * (аудит 2026-10-18).
 *
 * Порядок: `X-Real-IP` (наш nginx ставит его из `$remote_addr`) → **последний** хоп
 * `X-Forwarded-For` (адрес, дописанный нашим же прокси) → `null` (заголовков нет —
 * например, запрос пришёл напрямую в приложение; тогда все клиенты в одном бакете,
 * и это честнее, чем верить первому встречному).
 *
 * За прокси со **своим** доверенным слоем (Cloudflare и т.п.) ни один из этих
 * заголовков не является адресом клиента — там нужен отдельный разбор цепочки.
 * Наш прод — один nginx, поэтому доверенный хоп один.
 *
 * **Почему отдельный модуль, а не `getRequestIpHash`.** Здесь нет ни `server-only`,
 * ни `node:crypto`: извлечение адреса нужно и коллекциям Payload (лимит заявок в
 * `beforeValidate`), а цепочка `payload.config → коллекции → ugc.ts → getRequestIpHash`
 * исполняется вне Next-сборки (`payload generate:types`, tsx) и падала на
 * `ERR_MODULE_NOT_FOUND: 'server-only'` — то есть ломала CI (`web-quality`).
 * Держать хеширование (которому нужен секрет и крипто) и разбор заголовка в одном
 * модуле нельзя: второй обязан быть импортируемым откуда угодно.
 */
export function extractClientIp(headers: Headers): string | null {
  const realIp = headers.get('x-real-ip')?.trim()
  if (realIp) return realIp

  const forwarded = headers.get('x-forwarded-for')
  if (forwarded) {
    const hops = forwarded
      .split(',')
      .map((hop) => hop.trim())
      .filter(Boolean)
    const last = hops[hops.length - 1]
    if (last) return last
  }

  return null
}
